package q536;

public class Main {
    public static void main(String[] args) {
        // for - loop
        for (int i = 1; i <= 15; i++) {
            System.out.print(i + " ");
        }
        System.out.println();

        // while loop
        int j = 1;
        while (j <= 15) {
            System.out.print(j + " ");
            j++;
        }
    }
}
